"""Print the web API's OpenAPI schema; the frontend generates its types from it.

uv run python -m calico.web.openapi > frontend/openapi.json
uv run python -m calico.web.openapi --fingerprint > frontend/src/api/fingerprint.ts
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from calico.settings import Settings
from calico.web.app import create_app
from calico.web.fingerprint import api_fingerprint


def _schema() -> dict[str, object]:
    # Settings are irrelevant to the schema; a throwaway home keeps this side-effect free.
    app = create_app(Settings(home=Path("/nonexistent-calico-home")), synchronous_jobs=True)
    return app.openapi()


def schema_json() -> str:
    return json.dumps(_schema(), indent=2, sort_keys=True)


def fingerprint_ts() -> str:
    """The page's copy of the schema's fingerprint (see ``calico.web.fingerprint``)."""
    return (
        "// Generated by `make api-types` from the server's schema. Do not edit.\n"
        f'export const API_FINGERPRINT = "{api_fingerprint(_schema())}";\n'
    )


def main() -> None:
    # This module's whole job is to print.
    if "--fingerprint" in sys.argv[1:]:
        print(fingerprint_ts(), end="")  # noqa: T201
    else:
        print(schema_json())  # noqa: T201


if __name__ == "__main__":
    main()
